func snow3gSbox(x uint32) uint32 {
	return uint32(snow3gS0[x>>24])<<24 | uint32(snow3gS1[(x>>16)&0xFF])<<16 |
		uint32(snow3gS0[(x>>8)&0xFF])<<8 | uint32(snow3gS1[x&0xFF])
}

// snow3gFsm — sub_427C：读 c[0..4]，写 c[0]/c[1]，返回 v4。
// 64 位拼接移位按 C uint64 语义（Go 同样先拼 64 位再移位后截断低 32 位）。
func snow3gFsm(c *[22]uint32) uint32 {
	v1 := c[1]
	v2 := c[3] + c[0]
	v3 := c[4] ^ v1
	v4 := (c[0] ^ c[2]) + v1
	v5 := (v2 << 16) | (v3 >> 16)
	v6 := v2 >> 14
	v7 := v2 >> 6
	v8 := v2 >> 16
	v9 := (v3 << 16) | (v2 >> 16)
	t1 := uint32((uint64(v3>>16)<<32 | uint64(v5)) >> 14)
	t2 := uint32((uint64(v3>>16)<<32 | uint64(v5)) >> 8)
	v10 := ((v6 & 3) | (4 * v5)) ^ v5 ^ ((v7 & 0x3FF) | (v5 << 10)) ^ t1 ^ t2
	t3 := uint32((uint64(v8)<<32 | uint64(v9)) >> 10)
	t4 := uint32((uint64(v8)<<32 | uint64(v9)) >> 2)
	v11 := (((v3 >> 8) & 0xFF) | (v9 << 8)) ^ v9 ^ (((v3 & 0xFFFF) >> 2) | (v9 << 14)) ^ t3 ^ t4
	c[0] = snow3gSbox(v10)
	c[1] = snow3gSbox(v11)
	return v4
}

// snow3gKeyschedule — sub_229C：初始化 + 32 轮预热（变量名照 C，勿改动顺序）。
func snow3gKeyschedule(c *[22]uint32, key, iv []byte) {
	for i := range c {
		c[i] = 0
	}
	for i := 0; i < 16; i++ {
		// iv[i]&0x807FFFFF 对 uint8 恒等（低 8 位全 1），照抄保留语义
		c[i+6] = (uint32(iv[i]) & 0x807FFFFF) | (uint32(key[i]) << 23) | ((snow3gD[i] & 0x7FFFFF) << 8)
	}
	v9 := c[21]
	v10 := c[20] & 0xFFFF
	v11 := c[17]
	v12 := c[15]
	v13 := c[13]
	v14 := c[11]
	v15 := c[8]
	v16 := c[6]
	for round := 0; round < 32; round++ {
		c[2] = (v10 & 0xFFFF) | (((v9 >> 15) & 0xFFFF) << 16)
		c[3] = (v12 >> 15) | (v11 << 16)
		c[4] = (v14 >> 15) | (v13 << 16)
		c[5] = (v16 >> 15) | (v15 << 16)
		v18 := snow3gFsm(c)
		v19hi := uint64(c[13])<<32 | uint64(c[12])
		v20 := uint64(c[20])<<32 | uint64(c[19])
		v15n := c[9]
		v16n := c[7]
		c[7] = c[8]
		v22lo := uint64(c[15])<<32 | uint64(c[14])
		v22hi := uint64(c[17])<<32 | uint64(c[16])
		v23 := (((c[6] & 0x7FFFFF) << 8) | (c[6] >> 23)) + c[6]
		v24 := (((c[10] & 0x7FF) << 20) | (c[10] >> 11)) + (v23 >> 31) + (v23 & 0x7FFFFFFF)
		v25 := (((c[16] & 0x3FF) << 21) | (c[16] >> 10)) + (v24 >> 31) + (v24 & 0x7FFFFFFF)
		v10n := c[21]
		v12n := uint32(v22hi & 0xFFFFFFFF)
		v26 := (((c[19] & 0x3FFF) << 17) | (c[19] >> 14)) + (v25 >> 31) + (v25 & 0x7FFFFFFF)
		v27 := (((v10n & 0xFFFF) << 15) | (v10n >> 16)) + (v26 >> 31) + (v26 & 0x7FFFFFFF)
		v11n := c[18]
		v28 := (v27 >> 31) + (v18 >> 1) + (v27 & 0x7FFFFFFF)
		v14n := uint32(v19hi & 0xFFFFFFFF)
		v13n := uint32(v22lo & 0xFFFFFFFF)
		v9n := (v28 & 0x7FFFFFFF) + (v28 >> 31)
		c[9] = c[10]
		c[10] = c[11]
		c[11] = c[12]
		c[12] = uint32(v19hi >> 32)
		c[18] = c[19]
		c[19] = uint32(v20 >> 32)
		c[6] = v16n
		c[8] = v15n
		c[13] = uint32(v22lo & 0xFFFFFFFF)
		c[14] = uint32(v22lo >> 32)
		c[15] = uint32(v22hi & 0xFFFFFFFF)
		c[16] = uint32(v22hi >> 32)
		c[17] = v11n
		c[20] = v10n
		c[21] = v9n
		v9, v10 = v9n, v10n
		v11, v12 = v11n, v12n
		v13, v14 = v13n, v14n
		v15, v16 = v15n, v16n
	}
}

// snow3gGenerate — sub_20F8：入口 FSM（丢弃输出）+ 逐字 XOR。
// ⚠️ 循环结构：先快照 → 状态前移 → if i >= blocks break → 装配 c[2..5] →
// ks = fsm ^ c[5] → XOR。break 在状态推进之后、keystream 计算之前。
// buf 同时作为输入与输出（照 C 的 in==out 同缓冲区；按字原地覆盖安全）。
func snow3gGenerate(c *[22]uint32, buf []byte, blocks int) {
	v4 := (c[15] >> 15) | (c[17] << 16)
	v5 := (c[11] >> 15) | (c[13] << 16)
	v6 := (c[6] >> 15) | (c[8] << 16)
	c[2] = (c[20] & 0xFFFF) | (((c[21] >> 15) & 0xFFFF) << 16)
	c[3] = v4
	c[4] = v5
	c[5] = v6
	snow3gFsm(c)
	for i := 0; ; i++ {
		rlo := uint64(c[11])<<32 | uint64(c[10])
		rhi := uint64(c[13])<<32 | uint64(c[12])
		v13 := c[7]
		v14 := c[18]
		v15 := c[19]
		v17 := c[20]
		v16 := c[21]
		v18 := c[6]
		c[7] = c[8]
		c[18] = v15
		c[19] = v17
		v19lo := uint64(c[15])<<32 | uint64(c[14])
		v19hi := uint64(c[17])<<32 | uint64(c[16])
		v20 := (((v18 & 0x7FFFFF) << 8) | (v18 >> 23)) + v18
		v21 := (((uint32(rlo) & 0x7FF) << 20) | (uint32(rlo) >> 11)) + (v20 >> 31) + (v20 & 0x7FFFFFFF)
		v22 := (((c[16] & 0x3FF) << 21) | (c[16] >> 10)) + (v21 >> 31) + (v21 & 0x7FFFFFFF)
		v23 := (((v15 & 0x3FFF) << 17) | (v15 >> 14)) + (v22 >> 31) + (v22 & 0x7FFFFFFF)
		v24 := c[9]
		v25 := (((v16 & 0xFFFF) << 15) | (v16 >> 16)) + (v23 >> 31) + (v23 & 0x7FFFFFFF)
		v26 := (v25 & 0x7FFFFFFF) + (v25 >> 31)
		oldC16 := c[16]
		c[6] = v13
		c[8] = v24
		c[9] = c[10]
		c[10] = c[11]
		c[11] = c[12]
		c[12] = uint32(rhi >> 32)
		c[13] = uint32(v19lo & 0xFFFFFFFF)
		c[14] = uint32(v19lo >> 32)
		c[15] = uint32(v19hi & 0xFFFFFFFF)
		c[16] = uint32(v19hi >> 32)
		c[17] = v14
		c[20] = v16
		c[21] = v26
		if i >= blocks {
			break
		}
		c[2] = (v16 & 0xFFFF) | (((v26 >> 15) & 0xFFFF) << 16)
		c[3] = (v14 << 16) | (oldC16 >> 15)
		c[4] = (uint32(v19lo) << 16) | (uint32(rhi) >> 15)
		c[5] = (v24 << 16) | (v13 >> 15)
		ks := snow3gFsm(c) ^ c[5]
		// C: bswap32(native-LE word) 读 == BE 读；bswap32(w) 存 native-LE == BE 写
		pt := binary.BigEndian.Uint32(buf[i*4 : i*4+4])
		binary.BigEndian.PutUint32(buf[i*4:i*4+4], pt^ks)
	}
}

// Snow3gVariant 实现 SNOW3G 变体流密码（新代 07E824B2）。
type Snow3gVariant struct{ key, iv []byte }

// NewSnow3gVariant 校验并构造：密钥调度直接索引 key[i]/iv[i]（i<16），
// 长度不足会在加密期 panic，这里在构造期即拒绝。
func NewSnow3gVariant(key, iv []byte) (*Snow3gVariant, error) {
	if len(key) != 16 {
		return nil, fmt.Errorf("snow3g key len %d != 16", len(key))
	}
	if len(iv) != 16 {
		return nil, fmt.Errorf("snow3g iv len %d != 16", len(iv))
	}
	return &Snow3gVariant{key: key, iv: iv}, nil
}

func (s *Snow3gVariant) Encrypt(text string) string {
	data := []byte(text)
	pad := 0
	if len(data)&3 != 0 {
		pad = 4 - (len(data) & 3)
	}
	total := len(data) + pad
	// C: 空输入 total=0 → 输出空（无填充块）
	buf := make([]byte, total)
	copy(buf, data)
	var c [22]uint32
	snow3gKeyschedule(&c, s.key, s.iv)
	snow3gGenerate(&c, buf, total/4)
	return hexEncode(buf)
}

func (s *Snow3gVariant) Decrypt(hexStr string) string {
	ct, err := hexDecode(hexStr)
	if err != nil {
		return ""
	}
	buf := make([]byte, len(ct))
	copy(buf, ct)
	var c [22]uint32
	snow3gKeyschedule(&c, s.key, s.iv)
	// C 语义：非 4 倍数静默截断尾部字节（保留原样，随后被去零截掉）
	snow3gGenerate(&c, buf, len(ct)/4)
	return string(stripTrailingZeros(buf))
}
