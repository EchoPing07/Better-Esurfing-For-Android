//
// 来源：算法验证/reference-c/snow3g_variant_android.c @ Ironjhin 0ffbf00
// （git blob SHA 34efaf47… 逐字节校验；上游经 unicorn 仿真对官方 .so 验证），
// 与 Esurfing-go-webui/cipher_snow3g.go 同源、经同一批 KAT 对拍。
// 密钥/IV = 旧 ZUC（B809531F）字节原样。
//
// 结构要点（与标准 SNOW 3G 完全不同的自研变体）：
//   - 状态 22 格 uint32（其中 c[2..5] 为每轮临时装配区）；
//   - 初始化：c[i+6] = iv[i] | key[i]<<23 | (D[i]&0x7FFFFF)<<8，32 轮预热；
//   - FSM：读 c[0..4]，写 c[0]/c[1]，返回 v4；双 S 盒（S0/S1 交替按字节）；
//   - generate：入口先装配 c[2..5] 并调一次 FSM（丢弃输出）；循环内
//     先推进状态、再判 break（i >= blocks）、之后才装配 c[2..5] 并算 keystream ——
//     这个顺序错任何一步整条流就错位；
//   - 字处理按 4 字节，补零到 4 倍数（已对齐不补块；空输入输出空，无填充块）；
//   - 解密对非 4 倍数输入按 C 语义静默截断尾部。

